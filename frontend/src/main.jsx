import { StrictMode } from 'react'
import { createRoot } from 'react-dom/client'
import './index.css'
import App from './App.jsx'
import ErrorBoundary from './components/ErrorBoundary'

// The boundary sits OUTSIDE <App />, so it also catches a throw from the
// providers and the router themselves — the failures that would otherwise
// leave a blank page with nothing mounted at all.
createRoot(document.getElementById('root')).render(
  <StrictMode>
    <ErrorBoundary>
      <App />
    </ErrorBoundary>
  </StrictMode>,
)
