export class TeamError extends HttpsError {
  constructor(code, extra = {}) {
    if (!GRPC[code]) throw new Error(`Unknown team error code: ${code}`)
    // `extra.message` (ADR-90) lets an operation name the specific reason — a
    // sentence composed by the generated domain module, never an internal
    // error. The stable `details.code` is unchanged by it.
    const { message, ...details } = extra
    super(GRPC[code], typeof message === 'string' && message.length > 0 ? message : MESSAGE[code], { code, ...details })
    this.teamCode = code
  }
}

export const fail = (code, extra) => { throw new TeamError(code, extra) }

export const isTeamError = (err, code) =>
  err instanceof HttpsError && err.details?.code === code
